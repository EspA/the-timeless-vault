export type Country = { code: string; name: string };

export const countryFlag = (code?: string | null) => {
  if (!code || code.length !== 2) return "";
  return [...code.toUpperCase()].map((char) => String.fromCodePoint(127397 + char.charCodeAt(0))).join("");
};

export const countryLabel = (code?: string | null) => {
  if (!code) return "";
  const country = COUNTRIES.find((row) => row.code === code.toUpperCase());
  const flag = countryFlag(code);
  const name = country?.name || code;
  return flag ? `${flag} ${name}` : name;
};

